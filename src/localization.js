export function translate(text, language) {
  if (language === "kn") return kannadaUi[text] ?? text;
  if (language === "hi") return hindiUi[text] ?? text;
  return text;
}

export function localizeScheme(scheme, language) {
  if (!scheme) return scheme;
  if (language === "kn") {
    return {
      ...scheme,
      ...kannadaSchemes[scheme.id],
      applicationGuidance: applicationGuidanceTranslations.kn[scheme.id] ?? scheme.applicationGuidance,
    };
  }
  if (language === "hi") {
    return {
      ...scheme,
      ...hindiSchemes[scheme.id],
      applicationGuidance: applicationGuidanceTranslations.hi[scheme.id] ?? scheme.applicationGuidance,
    };
  }
  return scheme;
}
